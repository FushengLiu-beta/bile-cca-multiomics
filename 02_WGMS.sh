# 1. Assess raw read quality
fastqc -t 60 input_R1.fq.gz input_R2.fq.gz
multiqc .

# 2. Trim adapters and filter low-quality reads
trim_galore -j 76 --illumina --paired --length 36 --gzip \
    --clip_R1 5 --clip_R2 5 \
    --three_prime_clip_R1 3 --three_prime_clip_R2 3 \
    --quality 30 \
    input_R1.fq.gz input_R2.fq.gz

# 3. Build the Bismark genome index (run once per reference)
# Place the reference FASTA file in genome_dir before indexing
bismark_genome_preparation --parallel 16 genome_dir

# 4. Align paired-end bisulfite reads
bismark -p 2 --gzip --score_min L,0,-0.2 \
    --genome genome_dir \
    -1 input_R1_val_1.fq.gz \
    -2 input_R2_val_2.fq.gz

# 5. Remove duplicate reads
# Replace aligned.bam with the BAM file generated by Bismark
deduplicate_bismark --paired --bam aligned.bam

# 6. Sort deduplicated alignments by genomic coordinates
samtools sort -@ 32 -l 6 -m 10G \
    aligned.deduplicated.bam \
    -o sorted.bam

# 7. Generate alignment statistics
samtools stats sorted.bam > alignment_stats.txt
multiqc .

# 8. Assess processed BAM quality
fastqc -t 60 sorted.bam
multiqc .

# 9. Build the BatMeth2 genome index (run once per reference)
BatMeth2 index -g reference.fa

# 10. Calculate methylation levels
BatMeth2 calmeth \
    -Q 30 --coverage 4 -nC 1 \
    --Regions 200 --step 50000 \
    --genome reference.fa \
    --binput sorted.bam \
    --methratio sample

# 11. Calculate gene body and promoter methylation
# Provide a BED5 annotation file with zero-based start coordinates
BatMeth2 methyGff \
    --coverage 4 -nC 1 \
    --genome reference.fa \
    -b5 genes.bed5 \
    --body --promoter --GENE \
    --distance 2000 --step 0.01 \
    --methratio sample.methratio.txt \
    --out sample.genes

# 12. Calculate transcript body and promoter methylation
BatMeth2 methyGff \
    --coverage 4 -nC 1 \
    --genome reference.fa \
    -b5 transcripts.bed5 \
    --body --promoter --GENE \
    --distance 1000 --step 0.01 \
    --methratio sample.methratio.txt \
    --out sample.transcripts